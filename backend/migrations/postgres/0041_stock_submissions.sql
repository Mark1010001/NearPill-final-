-- Stock a partner pharmacy wants to sell (CSV upload or single add) waits here until an admin reviews it.
-- Nothing in inventory changes until the admin approves.
CREATE TABLE IF NOT EXISTS stock_submissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drugstore_id INTEGER NOT NULL REFERENCES drugstores(id) ON DELETE CASCADE,
  submitted_by INTEGER NOT NULL REFERENCES users(id),
  source VARCHAR(8) NOT NULL CHECK (source IN ('csv', 'single')),
  status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  file_name VARCHAR(120),
  rows JSONB NOT NULL,
  row_count INTEGER NOT NULL CHECK (row_count BETWEEN 1 AND 500),
  review_note VARCHAR(500),
  reviewed_by INTEGER REFERENCES users(id),
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK ((status = 'pending' AND reviewed_at IS NULL) OR (status <> 'pending' AND reviewed_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS stock_submissions_status_idx ON stock_submissions (status, created_at DESC);
CREATE INDEX IF NOT EXISTS stock_submissions_store_idx ON stock_submissions (drugstore_id, created_at DESC);

GRANT SELECT, INSERT ON stock_submissions TO nearpill_app;
GRANT UPDATE (status, review_note, reviewed_by, reviewed_at) ON stock_submissions TO nearpill_app;

ALTER TABLE stock_submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_submissions FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS stock_submissions_select ON stock_submissions;
CREATE POLICY stock_submissions_select ON stock_submissions FOR SELECT TO nearpill_app
USING (
  nearpill.current_actor_role() IN ('admin','system')
  OR EXISTS (
    SELECT 1 FROM pharmacy_memberships pm
    WHERE pm.drugstore_id = stock_submissions.drugstore_id
      AND pm.user_id = nearpill.current_actor_id() AND pm.is_active = 1
  )
);

-- Only a member of the pharmacy can submit, always as pending and always as themselves.
DROP POLICY IF EXISTS stock_submissions_insert ON stock_submissions;
CREATE POLICY stock_submissions_insert ON stock_submissions FOR INSERT TO nearpill_app
WITH CHECK (
  nearpill.current_capability() = 'stock_submission'
  AND nearpill.current_actor_role() = 'partner'
  AND status = 'pending' AND reviewed_by IS NULL AND reviewed_at IS NULL
  AND submitted_by = nearpill.current_actor_id()
  AND EXISTS (
    SELECT 1 FROM pharmacy_memberships pm JOIN drugstores d ON d.id = pm.drugstore_id
    WHERE pm.drugstore_id = stock_submissions.drugstore_id
      AND pm.user_id = nearpill.current_actor_id() AND pm.is_active = 1
      AND d.is_active = 1 AND d.verification_status = 'verified'
  )
);

-- Only an admin can decide.
DROP POLICY IF EXISTS stock_submissions_review ON stock_submissions;
CREATE POLICY stock_submissions_review ON stock_submissions FOR UPDATE TO nearpill_app
USING (nearpill.current_actor_role() IN ('admin','system') AND nearpill.current_capability() = 'inventory_mutation')
WITH CHECK (nearpill.current_actor_role() IN ('admin','system') AND nearpill.current_capability() = 'inventory_mutation');

DROP POLICY IF EXISTS migrator_all ON stock_submissions;
CREATE POLICY migrator_all ON stock_submissions FOR ALL TO nearpill_migrator USING (true) WITH CHECK (true);
