-- Sign-up hardening: shared throttle counters for code sending, code checking and
-- account creation, plus a record of which terms version a customer accepted.
CREATE TABLE IF NOT EXISTS auth_throttle_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope VARCHAR(32) NOT NULL,
  key_hash CHAR(64) NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS auth_throttle_events_lookup_idx
  ON auth_throttle_events (scope, key_hash, occurred_at DESC);

GRANT SELECT, INSERT, UPDATE, DELETE ON auth_throttle_events TO nearpill_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO nearpill_app;
ALTER TABLE auth_throttle_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth_throttle_events FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS identity_security_app ON auth_throttle_events;
CREATE POLICY identity_security_app ON auth_throttle_events FOR ALL TO nearpill_app
  USING (nearpill.current_capability() = 'identity_security')
  WITH CHECK (nearpill.current_capability() = 'identity_security');
DROP POLICY IF EXISTS migrator_all ON auth_throttle_events;
CREATE POLICY migrator_all ON auth_throttle_events FOR ALL TO nearpill_migrator USING (true) WITH CHECK (true);

ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_accepted_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_version VARCHAR(40);
GRANT INSERT (terms_accepted_at, terms_version) ON users TO nearpill_app;
