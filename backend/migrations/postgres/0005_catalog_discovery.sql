-- OTC-only publication, pharmacy verification, indexed search, and bounded discovery.
-- Existing records are intentionally NOT trusted as published/verified evidence.

CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

CREATE SCHEMA IF NOT EXISTS nearpill_extensions;
REVOKE CREATE ON SCHEMA nearpill_extensions FROM PUBLIC;
CREATE EXTENSION IF NOT EXISTS cube WITH SCHEMA nearpill_extensions;
CREATE EXTENSION IF NOT EXISTS earthdistance WITH SCHEMA nearpill_extensions;
GRANT USAGE ON SCHEMA nearpill_extensions TO nearpill_app;

ALTER TABLE medicines
  ADD COLUMN IF NOT EXISTS publication_status VARCHAR(16) NOT NULL DEFAULT 'draft',
  ADD COLUMN IF NOT EXISTS published_at TIMESTAMPTZ;

ALTER TABLE medicines
  DROP CONSTRAINT IF EXISTS medicines_publication_status_check;
ALTER TABLE medicines
  ADD CONSTRAINT medicines_publication_status_check
  CHECK (publication_status IN ('draft','published','retired'));

-- Prescription/Rx rows from the legacy schema are retired, never auto-published.
UPDATE medicines
SET publication_status = CASE WHEN rx_required = 1 THEN 'retired' ELSE 'draft' END,
    published_at = NULL
WHERE publication_status = 'draft';

ALTER TABLE medicines DROP COLUMN IF EXISTS rx_required;

CREATE TABLE IF NOT EXISTS medicine_evidence (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medicine_id INTEGER NOT NULL REFERENCES medicines(id) ON DELETE CASCADE,
  source_name VARCHAR(200) NOT NULL,
  source_url TEXT NOT NULL,
  source_version VARCHAR(120),
  status VARCHAR(16) NOT NULL DEFAULT 'approved' CHECK (status IN ('approved','rejected')),
  reviewed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE drugstores
  ADD COLUMN IF NOT EXISTS verification_status VARCHAR(16) NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS verified_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS public_profile_published_at TIMESTAMPTZ;

ALTER TABLE drugstores
  DROP CONSTRAINT IF EXISTS drugstores_verification_status_check;
ALTER TABLE drugstores
  ADD CONSTRAINT drugstores_verification_status_check
  CHECK (verification_status IN ('pending','verified','rejected'));

-- Legacy/demo pharmacy records must be explicitly reviewed before public exposure.
UPDATE drugstores
SET verification_status = 'pending',
    verified_at = NULL,
    public_profile_published_at = NULL
WHERE verification_status = 'pending';

CREATE TABLE IF NOT EXISTS pharmacy_verifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drugstore_id INTEGER NOT NULL REFERENCES drugstores(id) ON DELETE CASCADE,
  status VARCHAR(16) NOT NULL CHECK (status IN ('pending','verified','rejected')),
  license_number VARCHAR(160),
  evidence_reference TEXT,
  notes TEXT,
  reviewed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE medicines
  ADD COLUMN IF NOT EXISTS search_document TSVECTOR
  GENERATED ALWAYS AS (
    setweight(to_tsvector('simple', COALESCE(brand_name, '')), 'A') ||
    setweight(to_tsvector('simple', COALESCE(generic_name, '')), 'A') ||
    setweight(to_tsvector('simple', COALESCE(category, '')), 'B') ||
    setweight(to_tsvector('simple', COALESCE(description, '')), 'C')
  ) STORED;

CREATE INDEX IF NOT EXISTS medicines_search_document_gin_idx
  ON medicines USING GIN (search_document);
CREATE INDEX IF NOT EXISTS medicines_brand_trgm_idx
  ON medicines USING GIN (brand_name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS medicines_generic_trgm_idx
  ON medicines USING GIN (generic_name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS drugstores_name_trgm_idx
  ON drugstores USING GIN (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS drugstores_address_trgm_idx
  ON drugstores USING GIN (address gin_trgm_ops);
CREATE INDEX IF NOT EXISTS drugstores_location_gist_idx
  ON drugstores USING GIST (
    nearpill_extensions.ll_to_earth(latitude::DOUBLE PRECISION, longitude::DOUBLE PRECISION)
  );
CREATE INDEX IF NOT EXISTS medicines_publication_idx
  ON medicines (publication_status, published_at DESC);
CREATE INDEX IF NOT EXISTS medicine_evidence_medicine_status_idx
  ON medicine_evidence (medicine_id, status, reviewed_at DESC);
CREATE INDEX IF NOT EXISTS pharmacy_verifications_store_reviewed_idx
  ON pharmacy_verifications (drugstore_id, reviewed_at DESC);
CREATE INDEX IF NOT EXISTS drugstores_publication_idx
  ON drugstores (verification_status, public_profile_published_at, is_active);

GRANT SELECT, INSERT, UPDATE, DELETE ON medicine_evidence, pharmacy_verifications TO nearpill_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO nearpill_app;

ALTER TABLE medicine_evidence ENABLE ROW LEVEL SECURITY;
ALTER TABLE medicine_evidence FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS medicine_evidence_select ON medicine_evidence;
CREATE POLICY medicine_evidence_select ON medicine_evidence FOR SELECT TO nearpill_app
USING (
  nearpill.current_actor_role() IN ('admin','system')
  OR (
    status = 'approved'
    AND EXISTS (
      SELECT 1 FROM medicines m
      WHERE m.id = medicine_id AND m.publication_status = 'published'
    )
  )
);
DROP POLICY IF EXISTS medicine_evidence_write ON medicine_evidence;
CREATE POLICY medicine_evidence_write ON medicine_evidence FOR ALL TO nearpill_app
USING (nearpill.current_actor_role() IN ('admin','system'))
WITH CHECK (nearpill.current_actor_role() IN ('admin','system'));
DROP POLICY IF EXISTS migrator_all ON medicine_evidence;
CREATE POLICY migrator_all ON medicine_evidence FOR ALL TO nearpill_migrator USING (true) WITH CHECK (true);

ALTER TABLE pharmacy_verifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE pharmacy_verifications FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS pharmacy_verifications_select ON pharmacy_verifications;
CREATE POLICY pharmacy_verifications_select ON pharmacy_verifications FOR SELECT TO nearpill_app
USING (
  nearpill.current_actor_role() IN ('admin','system')
  OR EXISTS (
    SELECT 1 FROM pharmacy_memberships pm
    WHERE pm.drugstore_id = pharmacy_verifications.drugstore_id
      AND pm.user_id = nearpill.current_actor_id()
      AND pm.is_active = 1
  )
);
DROP POLICY IF EXISTS pharmacy_verifications_write ON pharmacy_verifications;
CREATE POLICY pharmacy_verifications_write ON pharmacy_verifications FOR ALL TO nearpill_app
USING (nearpill.current_actor_role() IN ('admin','system'))
WITH CHECK (nearpill.current_actor_role() IN ('admin','system'));
DROP POLICY IF EXISTS migrator_all ON pharmacy_verifications;
CREATE POLICY migrator_all ON pharmacy_verifications FOR ALL TO nearpill_migrator USING (true) WITH CHECK (true);

-- Public pharmacy reads are now restricted to explicitly verified/published profiles.
DROP POLICY IF EXISTS drugstores_select ON drugstores;
CREATE POLICY drugstores_select ON drugstores FOR SELECT TO nearpill_app
USING (
  (is_active = 1 AND verification_status = 'verified' AND public_profile_published_at IS NOT NULL)
  OR nearpill.current_actor_role() IN ('admin','system')
  OR EXISTS (
    SELECT 1 FROM pharmacy_memberships pm
    WHERE pm.drugstore_id = id
      AND pm.user_id = nearpill.current_actor_id()
      AND pm.is_active = 1
  )
);

-- Public catalog reads are OTC-only by construction: the Rx flag is gone and only published rows are visible.
DROP POLICY IF EXISTS medicines_select ON medicines;
CREATE POLICY medicines_select ON medicines FOR SELECT TO nearpill_app
USING (
  publication_status = 'published'
  OR nearpill.current_actor_role() IN ('admin','system')
  OR nearpill.current_capability() = 'order_mutation'
);

-- Anonymous inventory reads require both a published medicine and a verified public pharmacy.
DROP POLICY IF EXISTS inventory_select ON inventory;
CREATE POLICY inventory_select ON inventory FOR SELECT TO nearpill_app
USING (
  nearpill.current_actor_role() IN ('admin','system')
  OR nearpill.current_capability() = 'order_mutation'
  OR EXISTS (
    SELECT 1 FROM pharmacy_memberships pm
    WHERE pm.drugstore_id = inventory.drugstore_id
      AND pm.user_id = nearpill.current_actor_id()
      AND pm.is_active = 1
  )
  OR (
    EXISTS (
      SELECT 1 FROM drugstores d
      WHERE d.id = inventory.drugstore_id
        AND d.is_active = 1
        AND d.verification_status = 'verified'
        AND d.public_profile_published_at IS NOT NULL
    )
    AND EXISTS (
      SELECT 1 FROM medicines m
      WHERE m.id = inventory.medicine_id
        AND m.publication_status = 'published'
    )
  )
);
