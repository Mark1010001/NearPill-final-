-- Transactionally correct checkout foundation: integer centavos, reservations,
-- stock movement ledger, one-pharmacy orders, idempotency, and centralized lifecycle states.

ALTER TABLE inventory
  ADD COLUMN IF NOT EXISTS price_centavos BIGINT,
  ADD COLUMN IF NOT EXISTS stock_on_hand INTEGER,
  ADD COLUMN IF NOT EXISTS reserved_quantity INTEGER NOT NULL DEFAULT 0;

UPDATE inventory
SET price_centavos = COALESCE(price_centavos, ROUND(price * 100)::BIGINT),
    stock_on_hand = COALESCE(stock_on_hand, stock_count);

ALTER TABLE inventory
  ALTER COLUMN price_centavos SET NOT NULL,
  ALTER COLUMN stock_on_hand SET NOT NULL;

ALTER TABLE inventory DROP CONSTRAINT IF EXISTS inventory_price_centavos_nonnegative;
ALTER TABLE inventory ADD CONSTRAINT inventory_price_centavos_nonnegative CHECK (price_centavos >= 0);
ALTER TABLE inventory DROP CONSTRAINT IF EXISTS inventory_stock_invariant;
ALTER TABLE inventory ADD CONSTRAINT inventory_stock_invariant
  CHECK (stock_on_hand >= 0 AND reserved_quantity >= 0 AND reserved_quantity <= stock_on_hand);

ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS total_centavos BIGINT,
  ADD COLUMN IF NOT EXISTS idempotency_key VARCHAR(128),
  ADD COLUMN IF NOT EXISTS idempotency_fingerprint VARCHAR(64);
UPDATE orders SET total_centavos = COALESCE(total_centavos, ROUND(total * 100)::BIGINT);
ALTER TABLE orders ALTER COLUMN total_centavos SET NOT NULL;
ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_total_centavos_nonnegative;
ALTER TABLE orders ADD CONSTRAINT orders_total_centavos_nonnegative CHECK (total_centavos >= 0);
CREATE UNIQUE INDEX IF NOT EXISTS orders_user_idempotency_unique
  ON orders (user_id, idempotency_key) WHERE idempotency_key IS NOT NULL;

UPDATE orders
SET status = CASE LOWER(status)
  WHEN 'pending' THEN 'reserved'
  WHEN 'approved' THEN 'confirmed'
  WHEN 'rejected' THEN 'cancelled'
  WHEN 'canceled' THEN 'cancelled'
  ELSE LOWER(status)
END;
UPDATE order_drugstores
SET status = CASE LOWER(status)
  WHEN 'pending' THEN 'reserved'
  WHEN 'approved' THEN 'confirmed'
  WHEN 'rejected' THEN 'cancelled'
  WHEN 'canceled' THEN 'cancelled'
  ELSE LOWER(status)
END;

ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_status_check;
ALTER TABLE orders ADD CONSTRAINT orders_status_check CHECK (status IN (
  'reserved','awaiting_payment','confirmed','preparing','ready_for_pickup',
  'cancellation_pending','cancelled','expired','completed'
));
ALTER TABLE order_drugstores DROP CONSTRAINT IF EXISTS order_drugstores_status_check;
ALTER TABLE order_drugstores ADD CONSTRAINT order_drugstores_status_check CHECK (status IN (
  'reserved','awaiting_payment','confirmed','preparing','ready_for_pickup',
  'cancellation_pending','cancelled','expired','completed'
));

ALTER TABLE order_items ADD COLUMN IF NOT EXISTS unit_price_centavos BIGINT;
UPDATE order_items SET unit_price_centavos = COALESCE(unit_price_centavos, ROUND(price * 100)::BIGINT);
ALTER TABLE order_items ALTER COLUMN unit_price_centavos SET NOT NULL;
ALTER TABLE order_items DROP CONSTRAINT IF EXISTS order_items_unit_price_centavos_nonnegative;
ALTER TABLE order_items ADD CONSTRAINT order_items_unit_price_centavos_nonnegative CHECK (unit_price_centavos >= 0);

ALTER TABLE payments ADD COLUMN IF NOT EXISTS amount_centavos BIGINT;
UPDATE payments SET amount_centavos = COALESCE(amount_centavos, ROUND(amount * 100)::BIGINT);
ALTER TABLE payments ALTER COLUMN amount_centavos SET NOT NULL;
ALTER TABLE payments DROP CONSTRAINT IF EXISTS payments_amount_centavos_nonnegative;
ALTER TABLE payments ADD CONSTRAINT payments_amount_centavos_nonnegative CHECK (amount_centavos >= 0);

CREATE TABLE IF NOT EXISTS reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  inventory_id INTEGER NOT NULL REFERENCES inventory(id) ON DELETE CASCADE,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  status VARCHAR(16) NOT NULL DEFAULT 'active' CHECK (status IN ('active','released','fulfilled')),
  released_at TIMESTAMPTZ,
  fulfilled_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT reservations_order_inventory_unique UNIQUE (order_id, inventory_id)
);

CREATE TABLE IF NOT EXISTS stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_id INTEGER NOT NULL REFERENCES inventory(id) ON DELETE CASCADE,
  order_id INTEGER REFERENCES orders(id) ON DELETE SET NULL,
  actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  movement_type VARCHAR(24) NOT NULL CHECK (movement_type IN ('adjustment','reserve','release','fulfill')),
  stock_on_hand_delta INTEGER NOT NULL DEFAULT 0,
  reserved_delta INTEGER NOT NULL DEFAULT 0,
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS inventory_store_sellable_idx
  ON inventory (drugstore_id, availability, stock_on_hand, reserved_quantity);
CREATE INDEX IF NOT EXISTS reservations_order_status_idx ON reservations(order_id, status);
CREATE INDEX IF NOT EXISTS reservations_inventory_status_idx ON reservations(inventory_id, status);
CREATE INDEX IF NOT EXISTS stock_movements_inventory_created_idx ON stock_movements(inventory_id, created_at DESC);
CREATE INDEX IF NOT EXISTS stock_movements_order_idx ON stock_movements(order_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON reservations, stock_movements TO nearpill_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO nearpill_app;

ALTER TABLE reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservations FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS reservations_app ON reservations;
CREATE POLICY reservations_app ON reservations FOR ALL TO nearpill_app
USING (
  nearpill.current_actor_role() IN ('admin','system')
  OR nearpill.current_capability() = 'order_mutation'
  OR EXISTS (SELECT 1 FROM orders o WHERE o.id = order_id AND o.user_id = nearpill.current_actor_id())
  OR EXISTS (
    SELECT 1 FROM inventory i JOIN pharmacy_memberships pm ON pm.drugstore_id = i.drugstore_id
    WHERE i.id = inventory_id AND pm.user_id = nearpill.current_actor_id() AND pm.is_active = 1
  )
)
WITH CHECK (
  nearpill.current_actor_role() IN ('admin','system')
  OR nearpill.current_capability() = 'order_mutation'
);
DROP POLICY IF EXISTS migrator_all ON reservations;
CREATE POLICY migrator_all ON reservations FOR ALL TO nearpill_migrator USING (true) WITH CHECK (true);

ALTER TABLE stock_movements ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_movements FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS stock_movements_select ON stock_movements;
CREATE POLICY stock_movements_select ON stock_movements FOR SELECT TO nearpill_app
USING (
  nearpill.current_actor_role() IN ('admin','system')
  OR nearpill.current_capability() = 'order_mutation'
  OR EXISTS (
    SELECT 1 FROM inventory i JOIN pharmacy_memberships pm ON pm.drugstore_id = i.drugstore_id
    WHERE i.id = inventory_id AND pm.user_id = nearpill.current_actor_id() AND pm.is_active = 1
  )
);
DROP POLICY IF EXISTS stock_movements_write ON stock_movements;
CREATE POLICY stock_movements_write ON stock_movements FOR INSERT TO nearpill_app
WITH CHECK (
  nearpill.current_actor_role() IN ('admin','system')
  OR nearpill.current_capability() IN ('order_mutation','inventory_mutation')
);
DROP POLICY IF EXISTS migrator_all ON stock_movements;
CREATE POLICY migrator_all ON stock_movements FOR ALL TO nearpill_migrator USING (true) WITH CHECK (true);

