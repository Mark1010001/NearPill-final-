CREATE TABLE IF NOT EXISTS auth_session_families (
  id VARCHAR(64) PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  revoked_at TIMESTAMPTZ,
  revoke_reason VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS auth_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  family_id VARCHAR(64) REFERENCES auth_session_families(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  token_kind VARCHAR(16) NOT NULL CHECK (token_kind IN ('access','refresh','web')),
  csrf_hash CHAR(64),
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK ((token_kind = 'web' AND csrf_hash IS NOT NULL) OR token_kind <> 'web')
);

CREATE INDEX IF NOT EXISTS auth_sessions_user_idx ON auth_sessions (user_id, expires_at DESC);
CREATE INDEX IF NOT EXISTS auth_sessions_family_idx ON auth_sessions (family_id);

CREATE TABLE IF NOT EXISTS email_verification_challenges (
  email VARCHAR(254) PRIMARY KEY,
  code_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  verified_at TIMESTAMPTZ,
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS password_reset_challenges (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  email VARCHAR(254) NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS password_reset_active_user_idx
  ON password_reset_challenges (user_id)
  WHERE consumed_at IS NULL;

CREATE TABLE IF NOT EXISTS auth_rate_limit_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope VARCHAR(16) NOT NULL CHECK (scope IN ('ip')),
  key_hash CHAR(64) NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS auth_rate_limit_events_lookup_idx
  ON auth_rate_limit_events (scope, key_hash, occurred_at DESC);

CREATE TABLE IF NOT EXISTS auth_account_security (
  email_hash CHAR(64) PRIMARY KEY,
  failures INTEGER NOT NULL DEFAULT 0 CHECK (failures >= 0),
  next_allowed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL,
  in_flight_until TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

GRANT SELECT, INSERT, UPDATE, DELETE ON auth_session_families, auth_sessions,
  email_verification_challenges, password_reset_challenges,
  auth_rate_limit_events, auth_account_security TO nearpill_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO nearpill_app;

DO $$
DECLARE
  security_table TEXT;
BEGIN
  FOREACH security_table IN ARRAY ARRAY[
    'auth_session_families','auth_sessions','email_verification_challenges',
    'password_reset_challenges','auth_rate_limit_events','auth_account_security'
  ]
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', security_table);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', security_table);
    EXECUTE format('DROP POLICY IF EXISTS identity_security_app ON %I', security_table);
    EXECUTE format(
      'CREATE POLICY identity_security_app ON %I FOR ALL TO nearpill_app USING (nearpill.current_capability() = ''identity_security'') WITH CHECK (nearpill.current_capability() = ''identity_security'')',
      security_table
    );
    EXECUTE format('DROP POLICY IF EXISTS migrator_all ON %I', security_table);
    EXECUTE format(
      'CREATE POLICY migrator_all ON %I FOR ALL TO nearpill_migrator USING (true) WITH CHECK (true)',
      security_table
    );
  END LOOP;
END
$$;

-- Pharmacy members can read only order records linked to their active pharmacy membership.
DROP POLICY IF EXISTS orders_select ON orders;
CREATE POLICY orders_select ON orders FOR SELECT TO nearpill_app
USING (
  user_id = nearpill.current_actor_id()
  OR nearpill.current_actor_role() IN ('admin','system')
  OR EXISTS (
    SELECT 1
    FROM order_drugstores od
    JOIN pharmacy_memberships pm ON pm.drugstore_id = od.drugstore_id
    WHERE od.order_id = orders.id
      AND pm.user_id = nearpill.current_actor_id()
      AND pm.is_active = 1
  )
);

DROP POLICY IF EXISTS order_drugstores_access ON order_drugstores;
DROP POLICY IF EXISTS order_drugstores_select ON order_drugstores;
CREATE POLICY order_drugstores_select ON order_drugstores FOR SELECT TO nearpill_app
USING (
  nearpill.current_actor_role() IN ('admin','system')
  OR EXISTS (SELECT 1 FROM orders o WHERE o.id = order_id AND o.user_id = nearpill.current_actor_id())
  OR EXISTS (
    SELECT 1 FROM pharmacy_memberships pm
    WHERE pm.drugstore_id = order_drugstores.drugstore_id
      AND pm.user_id = nearpill.current_actor_id()
      AND pm.is_active = 1
  )
);
CREATE POLICY order_drugstores_insert ON order_drugstores FOR INSERT TO nearpill_app
WITH CHECK (
  nearpill.current_actor_role() IN ('admin','system')
  OR EXISTS (SELECT 1 FROM orders o WHERE o.id = order_id AND o.user_id = nearpill.current_actor_id())
);
CREATE POLICY order_drugstores_update ON order_drugstores FOR UPDATE TO nearpill_app
USING (
  nearpill.current_actor_role() IN ('admin','system')
  OR EXISTS (SELECT 1 FROM orders o WHERE o.id = order_id AND o.user_id = nearpill.current_actor_id())
)
WITH CHECK (
  nearpill.current_actor_role() IN ('admin','system')
  OR EXISTS (SELECT 1 FROM orders o WHERE o.id = order_id AND o.user_id = nearpill.current_actor_id())
);

