-- Backfill only the entitlement already implied by the existing Premium reporting product behavior.
INSERT INTO subscription_entitlements (drugstore_id, subscription_id, entitlement_key)
SELECT s.drugstore_id, s.id, 'reports:view:premium'
FROM subscriptions s
WHERE s.tier = 'Premium' AND s.status = 'active'
  AND (s.end_date IS NULL OR s.end_date >= CURRENT_DATE)
  AND NOT EXISTS (
    SELECT 1 FROM subscription_entitlements e
    WHERE e.drugstore_id = s.drugstore_id
      AND e.entitlement_key = 'reports:view:premium'
      AND e.revoked_at IS NULL
  );
