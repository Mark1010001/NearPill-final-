-- Provider-backed payment/refund/reconciliation and subscription entitlement authority.
-- No concrete provider or deposit percentage is selected here; those remain runtime owner decisions.

ALTER TABLE payments
  ADD COLUMN IF NOT EXISTS currency VARCHAR(3) NOT NULL DEFAULT 'PHP',
  ADD COLUMN IF NOT EXISTS provider VARCHAR(64),
  ADD COLUMN IF NOT EXISTS provider_payment_id VARCHAR(200),
  ADD COLUMN IF NOT EXISTS payment_plan VARCHAR(32),
  ADD COLUMN IF NOT EXISTS policy_version VARCHAR(100),
  ADD COLUMN IF NOT EXISTS idempotency_key VARCHAR(128),
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Remove synthetic pending rows created by the pre-provider compatibility path.
DELETE FROM payments
WHERE payment_status = 'pending'
  AND provider_payment_id IS NULL;

-- Legacy local assertions of money movement are not accepted as provider truth.
UPDATE payments
SET payment_status = 'reconciliation_required',
    provider = COALESCE(provider, 'legacy-local'),
    updated_at = CURRENT_TIMESTAMP
WHERE payment_status IN ('paid','refunded')
  AND provider_payment_id IS NULL;

UPDATE payments
SET payment_status = 'failed', provider = COALESCE(provider, 'legacy-local'), updated_at = CURRENT_TIMESTAMP
WHERE payment_status = 'failed' AND provider IS NULL;

ALTER TABLE payments DROP CONSTRAINT IF EXISTS payments_status_check;
ALTER TABLE payments ADD CONSTRAINT payments_status_check CHECK (payment_status IN (
  'pending','confirmed','failed','refund_pending','refunded','reconciliation_required'
));
ALTER TABLE payments DROP CONSTRAINT IF EXISTS payments_currency_check;
ALTER TABLE payments ADD CONSTRAINT payments_currency_check CHECK (currency = 'PHP');
CREATE UNIQUE INDEX IF NOT EXISTS payments_provider_external_unique
  ON payments(provider, provider_payment_id)
  WHERE provider IS NOT NULL AND provider_payment_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS payments_order_idempotency_unique
  ON payments(order_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS payment_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider VARCHAR(64) NOT NULL,
  event_id VARCHAR(200) NOT NULL,
  event_type VARCHAR(64) NOT NULL,
  provider_payment_id VARCHAR(200),
  provider_refund_id VARCHAR(200),
  amount_centavos BIGINT CHECK (amount_centavos IS NULL OR amount_centavos >= 0),
  currency VARCHAR(3),
  raw_body_hash VARCHAR(64) NOT NULL,
  occurred_at TIMESTAMPTZ,
  processing_status VARCHAR(32) NOT NULL DEFAULT 'received' CHECK (processing_status IN ('received','processed','reconciliation_required')),
  processed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT payment_events_provider_event_unique UNIQUE(provider, event_id)
);

CREATE TABLE IF NOT EXISTS refunds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
  amount_centavos BIGINT NOT NULL CHECK (amount_centavos > 0),
  provider VARCHAR(64) NOT NULL,
  provider_refund_id VARCHAR(200) NOT NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','failed')),
  reason TEXT NOT NULL,
  requested_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  confirmed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT refunds_provider_external_unique UNIQUE(provider, provider_refund_id),
  CONSTRAINT refunds_provider_idempotency_unique UNIQUE(provider, idempotency_key)
);

CREATE TABLE IF NOT EXISTS payment_reconciliation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER REFERENCES payments(id) ON DELETE CASCADE,
  provider VARCHAR(64) NOT NULL,
  event_id VARCHAR(200),
  reason VARCHAR(120) NOT NULL,
  details TEXT,
  status VARCHAR(24) NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved')),
  resolved_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  resolved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE subscriptions ADD COLUMN IF NOT EXISTS plan_version VARCHAR(100) NOT NULL DEFAULT 'legacy-v1';

CREATE TABLE IF NOT EXISTS subscription_entitlements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drugstore_id INTEGER NOT NULL REFERENCES drugstores(id) ON DELETE CASCADE,
  subscription_id INTEGER NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
  entitlement_key VARCHAR(100) NOT NULL,
  granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revoked_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS subscription_entitlements_active_unique
  ON subscription_entitlements(drugstore_id, entitlement_key)
  WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS billing_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drugstore_id INTEGER NOT NULL REFERENCES drugstores(id) ON DELETE CASCADE,
  subscription_id INTEGER REFERENCES subscriptions(id) ON DELETE SET NULL,
  actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  event_type VARCHAR(100) NOT NULL,
  details TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS payment_events_payment_idx ON payment_events(provider, provider_payment_id, created_at DESC);
CREATE INDEX IF NOT EXISTS refunds_payment_status_idx ON refunds(payment_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS payment_reconciliation_open_idx ON payment_reconciliation(status, created_at DESC);
CREATE INDEX IF NOT EXISTS subscription_entitlements_store_idx ON subscription_entitlements(drugstore_id, revoked_at);
CREATE INDEX IF NOT EXISTS billing_events_store_created_idx ON billing_events(drugstore_id, created_at DESC);

GRANT SELECT, INSERT, UPDATE ON payments, payment_events, refunds, payment_reconciliation,
  subscriptions, subscription_entitlements, billing_events TO nearpill_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO nearpill_app;

DROP POLICY IF EXISTS payments_insert ON payments;
DROP POLICY IF EXISTS payments_update ON payments;
CREATE POLICY payments_insert ON payments FOR INSERT TO nearpill_app
WITH CHECK (
  nearpill.current_actor_role() IN ('admin','system')
  OR (
    nearpill.current_capability() = 'payment_mutation'
    AND EXISTS (SELECT 1 FROM orders o WHERE o.id = order_id AND o.user_id = nearpill.current_actor_id())
  )
);
CREATE POLICY payments_update ON payments FOR UPDATE TO nearpill_app
USING (
  nearpill.current_actor_role() IN ('admin','system')
  OR (
    nearpill.current_capability() = 'payment_mutation'
    AND (
      nearpill.current_actor_id() IS NULL
      OR EXISTS (SELECT 1 FROM orders o WHERE o.id = order_id AND o.user_id = nearpill.current_actor_id())
    )
  )
)
WITH CHECK (
  nearpill.current_actor_role() IN ('admin','system')
  OR (
    nearpill.current_capability() = 'payment_mutation'
    AND (
      nearpill.current_actor_id() IS NULL
      OR EXISTS (SELECT 1 FROM orders o WHERE o.id = order_id AND o.user_id = nearpill.current_actor_id())
    )
  )
);

