"""Generates the web and Flutter icon sources from icons.py (single source of truth)."""
import re, math, json, sys
import sys, os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from icons import ICONS

NUM = re.compile(r'[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?')

def tokenize(d):
    for m in re.finditer(r'([MmLlHhVvCcSsQqAaZz])|([-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?)', d):
        yield m.group(1) or float(m.group(2))

def arc_to_beziers(x1, y1, rx, ry, phi, fa, fs, x2, y2):
    if rx == 0 or ry == 0: return [('L', x2, y2)]
    phi = math.radians(phi); c, s = math.cos(phi), math.sin(phi)
    dx, dy = (x1-x2)/2, (y1-y2)/2
    x1p, y1p = c*dx + s*dy, -s*dx + c*dy
    rx, ry = abs(rx), abs(ry)
    lam = x1p**2/rx**2 + y1p**2/ry**2
    if lam > 1: rx *= math.sqrt(lam); ry *= math.sqrt(lam)
    num = rx**2*ry**2 - rx**2*y1p**2 - ry**2*x1p**2
    den = rx**2*y1p**2 + ry**2*x1p**2
    co = math.sqrt(max(0, num/den)) * (-1 if fa == fs else 1)
    cxp, cyp = co*rx*y1p/ry, -co*ry*x1p/rx
    cx = c*cxp - s*cyp + (x1+x2)/2; cy = s*cxp + c*cyp + (y1+y2)/2
    def ang(ux, uy, vx, vy):
        a = math.atan2(ux*vy - uy*vx, ux*vx + uy*vy); return a
    t1 = ang(1, 0, (x1p-cxp)/rx, (y1p-cyp)/ry)
    dt = ang((x1p-cxp)/rx, (y1p-cyp)/ry, (-x1p-cxp)/rx, (-y1p-cyp)/ry)
    if not fs and dt > 0: dt -= 2*math.pi
    if fs and dt < 0: dt += 2*math.pi
    n = max(1, math.ceil(abs(dt)/(math.pi/2) - 1e-9)); step = dt/n
    out = []
    k = 4/3*math.tan(step/4)
    for i in range(n):
        a1 = t1 + i*step; a2 = a1 + step
        def pt(a, r=1):
            x = rx*math.cos(a); y = ry*math.sin(a)
            return c*x - s*y + cx, s*x + c*y + cy
        def dv(a):
            x = -rx*math.sin(a); y = ry*math.cos(a)
            return c*x - s*y, s*x + c*y
        p1 = pt(a1); p2 = pt(a2); d1 = dv(a1); d2 = dv(a2)
        out.append(('C', p1[0]+k*d1[0], p1[1]+k*d1[1], p2[0]-k*d2[0], p2[1]-k*d2[1], p2[0], p2[1]))
    return out

def compile_path(d):
    toks = list(tokenize(d)); i = 0; cmd = None
    x = y = sx = sy = 0.0; lcx = lcy = None; ops = []
    def nums(n):
        nonlocal i
        v = toks[i:i+n]; i += n; return v
    while i < len(toks):
        if isinstance(toks[i], str): cmd = toks[i]; i += 1
        elif cmd in 'Mm': cmd = 'L' if cmd == 'M' else 'l'
        rel = cmd.islower(); C = cmd.upper()
        if C == 'Z':
            ops.append(('Z',)); x, y = sx, sy; lcx = None; continue
        if C == 'M':
            a, b = nums(2); x, y = (x+a, y+b) if rel else (a, b); sx, sy = x, y; ops.append(('M', x, y)); lcx = None
            cmd = 'l' if rel else 'L'; continue
        if C == 'L':
            a, b = nums(2); x, y = (x+a, y+b) if rel else (a, b); ops.append(('L', x, y)); lcx = None
        elif C == 'H':
            a, = nums(1); x = x+a if rel else a; ops.append(('L', x, y)); lcx = None
        elif C == 'V':
            a, = nums(1); y = y+a if rel else a; ops.append(('L', x, y)); lcx = None
        elif C == 'C':
            v = nums(6)
            if rel: v = [v[0]+x, v[1]+y, v[2]+x, v[3]+y, v[4]+x, v[5]+y]
            ops.append(('C', *v)); lcx, lcy = v[2], v[3]; x, y = v[4], v[5]
        elif C == 'S':
            v = nums(4)
            if rel: v = [v[0]+x, v[1]+y, v[2]+x, v[3]+y]
            c1 = (2*x-lcx, 2*y-lcy) if lcx is not None else (x, y)
            ops.append(('C', c1[0], c1[1], *v)); lcx, lcy = v[0], v[1]; x, y = v[2], v[3]
        elif C == 'A':
            rx, ry, ph, fa, fs, a, b = nums(7)
            nx, ny = (x+a, y+b) if rel else (a, b)
            ops += arc_to_beziers(x, y, rx, ry, ph, int(fa), int(fs), nx, ny); x, y = nx, ny; lcx = None
        else: raise ValueError(cmd)
    return ops

def fmt(v): 
    s = f'{v:.3f}'.rstrip('0').rstrip('.'); return '0' if s in ('-0', '') else s

def encode(ops):
    code = {'M': 0, 'L': 1, 'C': 2, 'Z': 3}; out = []
    for o in ops: out.append(fmt(code[o[0]])); out += [fmt(v) for v in o[1:]]
    return out

names = list(ICONS)
# --- Web ---
web = ["// GENERATED by tools/icons/gen.py from tools/icons/icons.py. Do not edit by hand.",
       "// NearPill icon set: 24px grid, 1.75 stroke, round caps and joins. Shared by the website and the Android app.",
       "export type NpIconDef = { s: string[]; f?: string[] };", "export const npIcons = {"]
for n in names:
    st = [s for s in ICONS[n] if isinstance(s, str)]; fl = [s[0] for s in ICONS[n] if not isinstance(s, str)]
    web.append(f"  {n}: {{ s: {json.dumps(st)}" + (f", f: {json.dumps(fl)}" if fl else "") + " },")
web += ["} as const satisfies Record<string, NpIconDef>;", "export type NpIconName = keyof typeof npIcons;", ""]
open('web/src/components/npIcons.ts', 'w').write('\n'.join(web))
# --- Dart ---
dart = ["// GENERATED by tools/icons/gen.py from tools/icons/icons.py. Do not edit by hand.",
        "// ignore_for_file: constant_identifier_names",
        "part of 'np_icon.dart';", "",
        "/// Path data per icon on a 24 x 24 grid. Ops: 0 = move, 1 = line, 2 = cubic, 3 = close.",
        "abstract final class NpIconSet {"]
for n in names:
    st = [encode(compile_path(s)) for s in ICONS[n] if isinstance(s, str)]
    fl = [encode(compile_path(s[0])) for s in ICONS[n] if not isinstance(s, str)]
    L = lambda rows: '[' + ', '.join('[' + ', '.join(r) + ']' for r in rows) + ']'
    dart.append(f"  static const {n} = NpIconData('{n}', {L(st)}" + (f", fills: {L(fl)}" if fl else "") + ");")
dart += ["}", ""]
open('lib/widgets/np_icons_data.dart', 'w').write('\n'.join(dart))
print(len(names))
